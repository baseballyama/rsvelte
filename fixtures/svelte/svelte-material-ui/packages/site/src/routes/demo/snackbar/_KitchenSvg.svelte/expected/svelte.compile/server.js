import * as $ from 'svelte/internal/server';
import { mdiCloseCircle } from '@mdi/js';
import Kitchen from '@smui/snackbar/kitchen';
import Button, { Label } from '@smui/button';

let counter = 0;

export default function _KitchenSvg($$renderer) {
	let kitchen;
	let reason = 'nothing yet';
	let action = 'nothing yet';

	function pushToKitchen() {
		kitchen.push({
			props: { variant: 'stacked' },
			label: "This is a snackbar generated by the custom icon kitchen. Here's a counter: " + ++counter,
			actions: [
				{ onClick: () => action = 'Something', text: 'Something' },
				{ onClick: () => action = 'Another', text: 'Another' }
			],
			dismissButton: true,
			onDismiss: () => action = 'Dismissed',
			onClose: (e) => {
				reason = e.detail.reason ?? 'Undefined.';
			}
		});
	}

	{
		function dismiss($$renderer) {
			$$renderer.push(`<path fill="currentColor"${$.attr('d', mdiCloseCircle)}></path>`);
		}

		Kitchen($$renderer, {
			dismissIcon$tag: 'svg',
			dismissIcon$viewBox: '0 0 24 24',
			dismiss,
			$$slots: { dismiss: true }
		});
	}

	$$renderer.push(`<!----> `);

	Button($$renderer, {
		onclick: pushToKitchen,
		children: ($$renderer) => {
			Label($$renderer, {
				children: ($$renderer) => {
					$$renderer.push(`<!---->Push a New Snackbar`);
				},
				$$slots: { default: true }
			});
		},
		$$slots: { default: true }
	});

	$$renderer.push(`<!----> <pre class="status">Closed Reason: ${$.escape(reason)}</pre> <pre class="status">Action: ${$.escape(action)}</pre>`);
}