import 'svelte/internal/disclose-version';
import * as $ from 'svelte/internal/client';
import Kitchen from '@smui/snackbar/kitchen';
import Button, { Label } from '@smui/button';

let counter = 0;
var root = $.from_html(`<!> <!> <pre class="status"> </pre> <pre class="status"> </pre>`, 1);

export default function _Kitchen($$anchor) {
	let kitchen;
	let reason = $.state('nothing yet');
	let action = $.state('nothing yet');

	function pushToKitchen() {
		kitchen.push({
			props: { variant: 'stacked' },
			label: "This is a snackbar generated by the kitchen. Here's a counter: " + ++counter,
			actions: [
				{ onClick: () => $.set(action, 'Something'), text: 'Something' },
				{ onClick: () => $.set(action, 'Another'), text: 'Another' }
			],
			dismissButton: true,
			onDismiss: () => $.set(action, 'Dismissed'),
			onClose: (e) => {
				$.set(reason, e.detail.reason ?? 'Undefined.', true);
			}
		});
	}

	var fragment = root();
	var node = $.first_child(fragment);

	$.bind_this(Kitchen(node, { dismissIcon$class: 'material-icons' }), ($$value) => kitchen = $$value, () => kitchen);

	var node_1 = $.sibling(node, 2);

	Button(node_1, {
		onclick: pushToKitchen,
		children: ($$anchor, $$slotProps) => {
			Label($$anchor, {
				children: ($$anchor, $$slotProps) => {
					$.next();

					var text = $.text('Push a New Snackbar');

					$.append($$anchor, text);
				},
				$$slots: { default: true }
			});
		},
		$$slots: { default: true }
	});

	var pre = $.sibling(node_1, 2);
	var text_1 = $.only_child(pre);
	var pre_1 = $.sibling(pre, 2);
	var text_2 = $.only_child(pre_1);

	$.template_effect(() => {
		$.set_text(text_1, `Closed Reason: ${$.get(reason) ?? ''}`);
		$.set_text(text_2, `Action: ${$.get(action) ?? ''}`);
	});

	$.append($$anchor, fragment);
}