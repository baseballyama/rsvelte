use super::{places, same_places};
use crate::compare::javascript::Unparsed;

#[test]
fn a_comment_is_keyed_by_its_text_and_its_neighbouring_tokens() {
    assert_eq!(
        places("let a = 1;\n// note\nf(\n\t/* x */ 'y'\n);").as_deref(),
        Ok(&["// note | ; ^ f".to_owned(), "/* x */ | ( ^ y".to_owned()][..])
    );
    assert_eq!(
        places("// only").as_deref(),
        Ok(&["// only | EOF ^ EOF".to_owned()][..])
    );
}

#[test]
fn layout_and_quotes_do_not_count() {
    assert_eq!(
        same_places("f('a', // c\n\tb);", "f(\n\t\"a\", // c\n\tb\n);\n"),
        Ok(true)
    );
    assert_eq!(
        same_places("/**\n * doc\n */\nf();", "/** * doc */ f();"),
        Ok(true)
    );
}

#[test]
fn a_moved_dropped_or_added_comment_counts() {
    // The comment moved from an argument to the next statement.
    assert_eq!(
        same_places("f(a, /* c */ b); g();", "f(a, b); /* c */ g();"),
        Ok(false)
    );
    assert_eq!(same_places("// c\nf();", "f();"), Ok(false));
    assert_eq!(same_places("f();", "// c\nf();"), Ok(false));
    // Two copies are not one.
    assert_eq!(same_places("// c\nf();", "// c\n// c\nf();"), Ok(false));
}

#[test]
fn pure_marks_and_the_module_header_are_left_out() {
    assert_eq!(
        same_places("/* @__PURE__ */ f();", "/*#__PURE__*/ f();"),
        Ok(true)
    );
    let header = "/* a.svelte.js generated by Svelte v5.57.3 */\nimport * as $ from 'svelte';";
    assert_eq!(
        same_places(header, "import * as $ from \"svelte\";"),
        Ok(true)
    );
    // The same text further down is a comment of the source.
    assert_eq!(
        same_places("f();\n/* x generated by Svelte v5 */", "f();"),
        Ok(false)
    );
}

#[test]
fn a_side_that_does_not_parse_is_named() {
    assert!(matches!(
        same_places("f(", "f();"),
        Err(Unparsed::Expected(_))
    ));
    assert!(matches!(
        same_places("f();", "f("),
        Err(Unparsed::Actual(_))
    ));
}
