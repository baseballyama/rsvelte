use super::{Difference, difference, places};
use crate::compare::javascript::Unparsed;

fn same(expected: &str, actual: &str) -> bool {
    difference(expected, actual).is_ok_and(|d| d.missing == 0 && d.extra == 0)
}

#[test]
fn a_comment_is_keyed_by_its_text_its_neighbours_and_for_a_line_comment_its_line() {
    assert_eq!(
        places("let a = 1;\n// note\nf(\n\t/* x */ 'y'\n);").as_deref(),
        Ok(&[
            "// note | a ; ^ f f | own line".to_owned(),
            "/* x */ | f ( ^ y EOF".to_owned()
        ][..])
    );
    assert_eq!(
        places("// only").as_deref(),
        Ok(&["// only | EOF EOF ^ EOF EOF | own line".to_owned()][..])
    );
}

#[test]
fn layout_and_quotes_do_not_count() {
    assert!(same("f('a', // c\n\tb);", "f(\n\t\"a\", // c\n\tb\n);\n"));
    assert!(same("/**\n * doc\n */\nf();", "/** * doc */ f();"));
    assert!(same("f(a, /* c */ b);", "f(\n\ta,\n\t/* c */ b\n);"));
}

#[test]
fn a_moved_dropped_or_added_comment_counts() {
    // The comment moved from an argument to the next statement.
    assert!(!same("f(a, /* c */ b); g();", "f(a, b); /* c */ g();"));
    assert!(!same("// c\nf();", "f();"));
    assert!(!same("f();", "// c\nf();"));
    // Two copies are not one.
    assert!(!same("// c\nf();", "// c\n// c\nf();"));
}

#[test]
fn a_move_between_like_tokens_counts() {
    // The same tokens on either side, so only the nearest words tell them apart.
    assert!(!same(
        "$.a(); /* c */ $.b(); $.d();",
        "$.a(); $.b(); /* c */ $.d();"
    ));
    assert!(!same(
        "function f() { /* c */ }\nfunction g() {}",
        "function f() {}\nfunction g() { /* c */ }"
    ));
    // A line comment that ends a statement's line, or that starts the next line.
    assert!(!same("a(); // c\nb();", "a();\n// c\nb();"));
}

#[test]
fn the_direction_of_a_difference_is_counted() {
    assert_eq!(
        difference("// c\nf();", "f();"),
        Ok(Difference {
            missing: 1,
            extra: 0
        })
    );
    assert_eq!(
        difference("f();", "// c\nf();"),
        Ok(Difference {
            missing: 0,
            extra: 1
        })
    );
    assert_eq!(
        difference("$.a(); /* c */ $.b();", "$.a(); $.b(); /* c */"),
        Ok(Difference {
            missing: 1,
            extra: 1
        })
    );
}

#[test]
fn pure_marks_and_the_module_header_are_left_out() {
    assert!(same("/* @__PURE__ */ f();", "/*#__PURE__*/ f();"));
    let header = "/* a.svelte.js generated by Svelte v5.57.3 */\nimport * as $ from 'svelte';";
    assert!(same(header, "import * as $ from \"svelte\";"));
    // The same text further down is a comment of the source.
    assert!(!same("f();\n/* x generated by Svelte v5 */", "f();"));
}

#[test]
fn a_side_that_does_not_parse_is_named() {
    assert!(matches!(
        difference("f(", "f();"),
        Err(Unparsed::Expected(_))
    ));
    assert!(matches!(difference("f();", "f("), Err(Unparsed::Actual(_))));
}
