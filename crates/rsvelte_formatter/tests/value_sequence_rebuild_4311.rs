#[test]
fn every_cell_formats_to_the_oracle_output() {
    let mut wrong = Vec::new();
    for (name, input, expected) in CELLS {
        let got = fmt(input);
        if got != *expected {
            wrong.push(format!("{name}: got {got:?}, want {expected:?}"));
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
}

/// Liveness: a continuation line has to carry a binary that the old budget
/// split (`parentRowId === row.id` whole on its line) and a chain has to cross
/// the wrap without splitting at every `?.`.
#[test]
fn the_table_carries_the_rebuilt_continuations() {
    let whole_binary = CELLS
        .iter()
        .filter(|(_, _, want)| want.lines().any(|l| l.trim() == "parentRowId === row.id"));
    let chain_whole = CELLS
        .iter()
        .filter(|(_, _, want)| want.contains("\n    ?.user?.email}'\""));
    let untouched = CELLS.iter().filter(|(_, input, want)| input == want);
    assert!(
        whole_binary.count() >= 1,
        "no cell keeps a binary whole on its continuation line"
    );
    assert!(
        chain_whole.count() >= 1,
        "no cell carries a chain across the wrap"
    );
    assert!(untouched.count() >= 1, "no cell is left untouched");
}

#[test]
fn the_oracle_output_is_a_fixed_point() {
    for (name, _, expected) in CELLS {
        assert_eq!(fmt(expected), *expected, "{name}");
    }
}
