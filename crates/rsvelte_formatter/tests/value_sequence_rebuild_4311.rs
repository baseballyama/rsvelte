//! The whole-value attribute model built each interpolation's broken form at
//! doc-build time, on a budget derived from the builder's running column —
//! the first line's room — and nothing re-checked it against the indent the
//! continuation lines print at (#4311). A continuation line that had the whole
//! width was broken again (`parentRowId ===` / `row.id`), and a member chain
//! split at every `?.`. The interpolations now carry their source, so the
//! printer rebuilds them at the attribute's real indent, `fits` charges them
//! up to their first break opportunity, and the closing `"` is charged the way
//! prettier charges it — by a measurement that reaches the value's end — rather
//! than as a column reserved on every line.
//!
//! Every expectation here was generated by running the input through the
//! oxfmt(`svelte: true`) oracle. The first three cells are the shapes of the
//! issue's carriers (a `class` with seven interpolations, a `message` whose
//! chain spans the wrap, a `title` with two `||` chains) and diverge without
//! the fix; `flat_control` must not move.

use rsvelte_formatter::{
    FormatOptions, IndentStyle, IndentWidth, JsFormatOptions, LineWidth, format,
};

fn fmt(src: &str) -> String {
    let js = JsFormatOptions {
        indent_style: IndentStyle::Space,
        indent_width: IndentWidth::try_from(2u8).unwrap(),
        line_width: LineWidth::try_from(80u16).unwrap(),
        ..JsFormatOptions::default()
    };
    let options = FormatOptions {
        js,
        typescript: false,
        ..FormatOptions::new()
    };
    format(src, &options).expect("format ok")
}

