//! Pins the `(code, message)` produced by every diagnostic constructor in `errors.rs` /
//! `warnings.rs`, so a wording or code change is caught here instead of only surfacing
//! if some fixture happens to exercise that exact wording. Error codes and message text
//! are part of the compatibility contract with official Svelte (PR #1751 compressed 197
//! of these into the declarative `diagnostics!` macro; see issue #1757).
//!
//! Mirrors the digest+count pattern in `visitors/shared/a11y/constants_test.rs` (#1743):
//! a pinned FNV-1a digest catches any change at a glance, and the pinned counts mean a
//! failure can say WHAT changed (a constructor added/removed) instead of just THAT
//! something changed.
//!
//! `errors::__diagnostics_dump()` / `warnings::__diagnostics_dump()` are generated by the
//! `diagnostics!` macro itself (see `diagnostic.rs`), so every constructor declared there
//! is automatically included — this test can only miss the handful of hand-written
//! constructors below the macro block (conditional message assembly), which are called
//! out individually instead.

use super::diagnostic::DiagnosticDump;
use super::errors;
use super::warnings;

/// Constructors declared inside the `diagnostics!` block in `errors.rs`.
const ERROR_MACRO_COUNT: usize = 126;
/// Constructors declared inside the `diagnostics!` block in `warnings.rs`.
const WARNING_MACRO_COUNT: usize = 73;
/// Calls below covering `errors.rs`'s hand-written constructor (`bind_invalid_name`),
/// one per `Option` branch.
const ERROR_HANDWRITTEN_CALLS: usize = 2;
/// Calls below covering `warnings.rs`'s hand-written constructors
/// (`state_referenced_locally`, `a11y_unknown_aria_attribute`, `a11y_unknown_role`,
/// `unknown_code`), one per `Option` branch.
const WARNING_HANDWRITTEN_CALLS: usize = 7;

/// FNV-1a 64 of `"<code>\t<message>\n"` for every entry `dump_all()` produces, in the
/// fixed order below. Pinned from this PR; if it legitimately changes, update it to the
/// value printed in the assertion failure after confirming the new wording is correct.
const DIAGNOSTICS_DIGEST: u64 = 0x02ac_e164_9652_e946;

fn fnv1a64(bytes: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    for &b in bytes {
        hash ^= b as u64;
        hash = hash.wrapping_mul(0x0000_0100_0000_01b3);
    }
    hash
}

fn dump<T: DiagnosticDump>(diagnostic: T) -> (String, String) {
    (
        diagnostic.dump_code().to_string(),
        diagnostic.dump_message().to_string(),
    )
}

/// Every diagnostic constructor, called with fixed placeholder arguments. Order is
/// deterministic (declaration order, then the hand-written calls below) so the digest
/// doesn't depend on hashing/iteration order.
fn dump_all() -> Vec<(String, String)> {
    let mut all = errors::__diagnostics_dump();
    all.push(dump(errors::bind_invalid_name("foo", Some("explanation"))));
    all.push(dump(errors::bind_invalid_name("foo", None)));

    all.extend(warnings::__diagnostics_dump());
    all.push(dump(warnings::state_referenced_locally(
        "foo",
        "$derived",
        Some(1),
        Some(2),
    )));
    all.push(dump(warnings::a11y_unknown_aria_attribute(
        "foo",
        Some("bar"),
    )));
    all.push(dump(warnings::a11y_unknown_aria_attribute("foo", None)));
    all.push(dump(warnings::a11y_unknown_role("foo", Some("bar"))));
    all.push(dump(warnings::a11y_unknown_role("foo", None)));
    all.push(dump(warnings::unknown_code("foo", Some("bar"))));
    all.push(dump(warnings::unknown_code("foo", None)));

    all
}

fn canonical_dump(all: &[(String, String)]) -> String {
    let mut out = String::new();
    for (code, message) in all {
        out.push_str(code);
        out.push('\t');
        out.push_str(message);
        out.push('\n');
    }
    out
}

#[test]
fn constructor_counts_are_pinned() {
    assert_eq!(
        errors::__diagnostics_dump().len(),
        ERROR_MACRO_COUNT,
        "a constructor was added to or removed from the `diagnostics!` block in errors.rs; \
         update ERROR_MACRO_COUNT and, if the digest test below now fails, DIAGNOSTICS_DIGEST"
    );
    assert_eq!(
        warnings::__diagnostics_dump().len(),
        WARNING_MACRO_COUNT,
        "a constructor was added to or removed from the `diagnostics!` block in warnings.rs; \
         update WARNING_MACRO_COUNT and, if the digest test below now fails, DIAGNOSTICS_DIGEST"
    );
    assert_eq!(
        dump_all().len(),
        ERROR_MACRO_COUNT
            + WARNING_MACRO_COUNT
            + ERROR_HANDWRITTEN_CALLS
            + WARNING_HANDWRITTEN_CALLS
    );
}

#[test]
fn diagnostic_codes_and_messages_are_pinned() {
    let dump = dump_all();
    let digest = fnv1a64(canonical_dump(&dump).as_bytes());
    assert_eq!(
        digest, DIAGNOSTICS_DIGEST,
        "a diagnostic's code or message text changed in errors.rs/warnings.rs (or one was \
         added, removed or reordered). If this is intentional, update DIAGNOSTICS_DIGEST in \
         diagnostics_test.rs to {digest:#x} after confirming the new wording matches official \
         Svelte."
    );
}
