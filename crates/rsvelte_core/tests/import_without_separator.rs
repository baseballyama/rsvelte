#[test]
fn side_effect_import_stays_first_in_a_module() {
    let src = r#"import"side-effect-pkg";
export const n = $state({v:0});"#;
    let expected = format!(
        r#"/* T.svelte.js generated by Svelte v{SVELTE_VERSION} */
import * as $ from 'svelte/internal/client';
import "side-effect-pkg";

export const n = $.proxy({{ v: 0 }});"#
    );
    assert_eq!(module(src, GenerateMode::Client, false), expected);
}

