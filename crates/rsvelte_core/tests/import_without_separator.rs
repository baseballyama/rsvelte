//! An `import` declaration needs no whitespace after the keyword: `import"pkg";`
//! is what Bun's TypeScript transpiler prints. The client's import extractor keyed
//! on the literal prefixes `import ` / `import{`, so such a statement stayed inside
//! the component function.
//!
//! Expected values are the official compiler's output for the same source.

use rsvelte_core::{CompileOptions, GenerateMode, ModuleCompileOptions, compile, compile_module};

/// The module banner carries the pinned Svelte version, so it is read from the
/// same place the compiler reads it rather than spelled again here.
const SVELTE_VERSION: &str = match option_env!("SVELTE_VERSION") {
    Some(version) => version,
    None => "VERSION",
};

fn component(src: &str, generate: GenerateMode, dev: bool) -> String {
    compile(
        src,
        CompileOptions {
            filename: Some("T.svelte".to_string()),
            generate,
            dev,
            ..Default::default()
        },
    )
    .expect("compile")
    .js
    .code
}

fn module(src: &str, generate: GenerateMode, dev: bool) -> String {
    compile_module(
        src,
        ModuleCompileOptions {
            filename: Some("T.svelte.js".to_string()),
            generate,
            dev,
            ..Default::default()
        },
    )
    .expect("compile_module")
    .js
    .code
}

#[test]
fn side_effect_import_hoists_on_the_client() {
    let src = r#"<script>import"side-effect-pkg";
let n = $state(0);</script>
<b>{n}</b>"#;
    let expected = r#"import 'svelte/internal/disclose-version';
import * as $ from 'svelte/internal/client';
import "side-effect-pkg";

var root = $.from_html(`<b></b>`);

export default function T($$anchor) {
	let n = 0;
	var b = root();

	b.textContent = '0';
	$.append($$anchor, b);
}"#;
    assert_eq!(component(src, GenerateMode::Client, false), expected);
}

#[test]
fn side_effect_import_hoists_on_the_client_in_dev() {
    let src = r#"<script>import"side-effect-pkg";
let n = $state(0);</script>
<b>{n}</b>"#;
    let expected = r#"import 'svelte/internal/disclose-version';

T[$.FILENAME] = 'T.svelte';

import * as $ from 'svelte/internal/client';
import "side-effect-pkg";

var root = $.add_locations($.from_html(`<b></b>`), T[$.FILENAME], [[3, 0]]);

export default function T($$anchor, $$props) {
	$.check_target(new.target);
	$.push($$props, true, T);

	let n = 0;
	var $$exports = { ...$.legacy_api() };
	var b = root();

	b.textContent = '0';
	$.append($$anchor, b);

	return $.pop($$exports);
}"#;
    assert_eq!(component(src, GenerateMode::Client, true), expected);
}

