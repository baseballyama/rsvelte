#[test]
fn import_property_key_on_its_own_line_is_not_a_declaration() {
    let src = r#"<script>
	const modules = import.meta.glob("./examples/*.svelte", {
		query: "?raw",
		import: "default",
		eager: true
	});
</script>

<b>{Object.keys(modules).length}</b>"#;
    let expected = r#"import 'svelte/internal/disclose-version';
import 'svelte/internal/flags/legacy';
import * as $ from 'svelte/internal/client';

var root = $.from_html(`<b> </b>`);

export default function T($$anchor, $$props) {
	$.push($$props, false);

	const modules = import.meta.glob("./examples/*.svelte", { query: "?raw", import: "default", eager: true });

	$.init();

	var b = root();
	var text = $.only_child(b, true);

	$.template_effect(($0) => $.set_text(text, $0), [() => Object.keys(modules).length]);
	$.append($$anchor, b);
	$.pop();
}"#;
    assert_eq!(component(src, GenerateMode::Client, false), expected);
}

#[test]
fn a_block_comment_after_the_keyword_may_close_on_a_later_line() {
    let src =
        "<script>\nimport /* a\n b */ x from \"m\";\nlet n = $state(x);\n</script>\n<b>{n}</b>";
    let expected = r#"import 'svelte/internal/disclose-version';
import * as $ from 'svelte/internal/client';
import x from "m";

var root = $.from_html(`<b> </b>`);

export default function T($$anchor) {
	/* a
	 b */
	let n = $.proxy(x);

	var b = root();
	var text = $.only_child(b, true);

	$.template_effect(() => $.set_text(text, n));
	$.append($$anchor, b);
}"#;
    assert_eq!(component(src, GenerateMode::Client, false), expected);
}
