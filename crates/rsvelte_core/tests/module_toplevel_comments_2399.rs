//! Top-level (Program-level) comments in the `.svelte.(js|ts)` module path.
//!
//! Upstream prints the generated program with esrap, and `client_module` /
//! `server_module` return a **synthesized** `Program` that has no `loc`.
//! esrap's `reset_comment_index` handles a body without a `loc` by parking the
//! comment cursor past the end of the comment list, so nothing is emitted at
//! Program level. Only a nested body that *does* have a `loc` (a function
//! block, a class body) rewinds the cursor — which is why comments inside a
//! function body survive, and why a top-level comment that follows such a
//! block survives too, the rewind having moved the cursor back onto it.
//!
//! `tests/module_comment_ownership.rs` covers the dropped side. What is pinned
//! *only* here is the preserved side of the same rule — `after_fn_toplevel` and
//! `inside_fn_then_two_top`, where a top-level comment following a located body
//! survives. Parking the cursor at the end of a located body passes every
//! assertion of that file and fails exactly those two, which is the shape a
//! blanket "drop every Program-level comment" fix degenerates into: measured
//! against upstream it is wrong in 112 of 192 generated slots (#2399).
//!
//! Every expectation here is the official compiler's byte-exact output, for
//! both `client` and `client-dev`.
//!
//! `server` is excluded: `transform_server_module` splices the transformed
//! source as text instead of printing an AST, so its comment (and margin)
//! placement is a separate divergence with a separate fix.

use rsvelte_core::compiler::ModuleCompileOptions;
use rsvelte_core::{GenerateMode, compile_module};

fn compile(src: &str, generate: GenerateMode, dev: bool) -> String {
    compile_module(
        src,
        ModuleCompileOptions {
            filename: Some("m.svelte.js".to_string()),
            generate,
            dev,
            ..Default::default()
        },
    )
    .expect("compile")
    .js
    .code
}

struct Case {
    name: &'static str,
    src: &'static str,
    client: &'static str,
    client_dev: &'static str,
}

/// Expectations carry the pinned Svelte version in their header comment;
/// substitute the version this crate was built against.
fn expected(template: &str) -> String {
    template.replace("__V__", option_env!("SVELTE_VERSION").unwrap_or("VERSION"))
}

