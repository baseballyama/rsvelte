#[test]
fn a_typescript_module_keeps_what_typescript_emits() {
    let compiled = |source| compile("a.svelte.ts", source, Target::Client);
    // An import of types only is still an import, for its side effects.
    assert_eq!(
        compiled("import { type A } from './a.js';\nlet a: A = $state(1);\nexport { a };\n"),
        "import * as $ from \"svelte/internal/client\";\nimport \"./a.js\";\nlet a = 1;\n\
         export { a };\n"
    );
    // A module whose exports are types stays a module.
    assert_eq!(
        compiled("import type { A } from './a.js';\nexport { type A };\nlet a = 1;\n"),
        "import * as $ from \"svelte/internal/client\";\nexport {};\nlet a = 1;\n"
    );
    assert_eq!(
        compiled("import type { A } from './a.js';\nlet a: A = 1;\n"),
        "import * as $ from \"svelte/internal/client\";\nlet a = 1;\nexport {};\n"
    );
    // A parameter property is a field the constructor sets.
    assert_eq!(
        compiled("export class A {\n\tconstructor(public x: number) {}\n}\n"),
        "import * as $ from \"svelte/internal/client\";\nexport class A {\n\tx;\n\tconstructor(x) \
         {\n\t\tthis.x = x;\n\t}\n}\n"
    );
    // A script is strict. TypeScript's directive lands after the import, where it is none, so it
    // prints as a string statement does.
    assert_eq!(
        compiled("let a: number = 1;\n"),
        "import * as $ from \"svelte/internal/client\";\n(\"use strict\");\nlet a = 1;\n"
    );
}

#[test]
fn a_module_keeps_its_prologue_after_the_runtime_import() {
    // svelte 5.59.1 `compileModule` keeps each directive as a statement where the import ends the
    // prologue; the parentheses keep the same tree.
    let compiled = |path, source| compile(path, source, Target::Client);
    let import = "import * as $ from \"svelte/internal/client\";\n";
    assert_eq!(
        compiled(
            "a.svelte.js",
            "\"use strict\";\n\"other\";\nimport { x } from \"y\";\nexport const a = $state(x);\n"
        ),
        format!(
            "{import}(\"use strict\");\n(\"other\");\nimport {{ x }} from \"y\";\n\
             export const a = $.proxy(x);\n"
        )
    );
    assert_eq!(
        compile("a.svelte.js", "'use strict'\n", Target::Server),
        "import * as $ from \"svelte/internal/server\";\n(\"use strict\");\n"
    );
    // TypeScript's emit puts `"use strict"` first in a script, once.
    assert_eq!(
        compiled("a.svelte.ts", "\"use client\";\nlet a: number = 1;\n"),
        format!("{import}(\"use strict\");\n(\"use client\");\nlet a = 1;\n")
    );
    assert_eq!(
        compiled("a.svelte.ts", "\"use strict\";\nlet a: number = 1;\n"),
        format!("{import}(\"use strict\");\nlet a = 1;\n")
    );
}

