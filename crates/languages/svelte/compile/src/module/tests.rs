/// What the task writes for `path` after the banner, or its diagnostics when it writes nothing.
fn compile(path: &str, source: &str, target: Target) -> String {
    let mut output = output(path, source, target);
    match output.files.pop() {
        Some(file) => {
            let name = path.rsplit('/').next().expect("a name");
            let banner = format!("/* {name} generated by Svelte v{VERSION} */\n");
            match file.text.strip_prefix(&banner) {
                Some(rest) => rest.to_owned(),
                None => panic!("no banner: {}", file.text),
            }
        }
        None => format!("{:?}", output.diagnostics),
    }
}

fn output(path: &str, source: &str, target: Target) -> TaskOutput {
    let mut registry = Registry::new();
    crate::register(&mut registry);
    let document = Document::new(path, source).expect("small");
    let task = CompileModule { target };
    let result = run(
        &registry,
        &[document],
        &RunOptions {
            tasks: &[task.identifier()],
            sharing: Sharing::Shared,
            threads: Some(1),
        },
    )
    .expect("valid plugins")
    .remove(0);
    let (_, output) = result.outputs.into_iter().next().expect("the task ran");
    output
}

