#[derive(Default)]
struct Written(Vec<Vec<u16>>);

impl Visit<'_> for Written {
    fn visit_string_literal(&mut self, it: &StringLiteral<'_>) {
        self.0.push(it.value.encode_utf16().collect());
    }

    fn visit_template_element(&mut self, it: &TemplateElement<'_>) {
        let cooked = it.value.cooked.expect("a printed template is cooked");
        self.0.push(cooked.encode_utf16().collect());
    }
}

fn strings(code: &str) -> Vec<Vec<u16>> {
    let allocator = Allocator::default();
    let parsed = Parser::new(&allocator, code, SourceType::mjs()).parse();
    assert!(!parsed.diagnostics.has_errors(), "{code}");
    let mut strings = Written::default();
    walk::walk_program(&mut strings, &parsed.program);
    let surrogate = |unit: &u16| (0xD800..0xE000).contains(unit);
    strings.0.retain(|units| units.iter().any(surrogate));
    strings.0.sort();
    strings.0
}

#[test]
fn a_lone_surrogate_is_folded_and_written_as_svelte_writes_it() {
    for &(source, client, server) in COMPONENTS {
        for (generate, expected) in [(Target::Client, client), (Target::Server, server)] {
            let options = CompileOptions {
                filename: "A.svelte".into(),
                generate,
                ..CompileOptions::default()
            };
            let code = compile(source, &options).expect(source).js.code;
            assert_eq!(strings(&code), expected, "{source:?} {generate:?}");
        }
    }
}
